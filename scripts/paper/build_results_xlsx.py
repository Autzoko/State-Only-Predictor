def write():
    wb = Workbook()
    wb.remove(wb.active)
    for name, title, cols, rows, widths in SHEETS:
        ws = wb.create_sheet(name)
        ws.append([title])
        ws["A1"].font = Font(bold=True, size=13)
        ws.append(cols)
        for c in ws[2]:
            c.font = Font(bold=True)
            c.alignment = Alignment(wrap_text=True, vertical="top")
        for r in rows:
            ws.append(r)
            row = ws[ws.max_row]
            first = str(r[0]) if r else ""
            fill = None
            if first.startswith("§"):
                fill = SEC_FILL
                row[0].font = Font(bold=True)
            elif any(isinstance(v, str) and ("待" in v) for v in r):
                fill = PEND_FILL
            elif any(v == "正文" or (isinstance(v, str) and v.startswith("正文")) for v in r):
                fill = MAIN_FILL
            for c in row:
                c.alignment = Alignment(wrap_text=True, vertical="top")
                if fill:
                    c.fill = fill
        ws.freeze_panes = "B3"
        for i, w in enumerate(widths or [], 1):
            ws.column_dimensions[get_column_letter(i)].width = w
    OUT.parent.mkdir(exist_ok=True)
    wb.save(OUT)
    print("wrote", OUT, [s[0] for s in SHEETS])


if __name__ == "__main__":
    write()
