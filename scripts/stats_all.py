#!/usr/bin/env python
"""Paper statistics from one manifest: every main / appendix comparison with the same protocol.

For each comparison (arms -> per-seed run names; episodes paired by (seed, task, init)):
  success rate per arm (mean +- sd over seeds), paired difference a - b in points with a 95% cluster-bootstrap CI
  (resampling (seed, task) clusters, 10k draws), pooled two-sided exact McNemar p, and Holm-adjusted p over the
  comparisons marked `primary` in the manifest.

  python scripts/stats_all.py --root <dir with outputs/<run>/rollouts*.json> --manifest configs/paper_manifest.json \
      --out docs/PAPER_STATS.md
Runs that are missing are reported as such (the comparison is skipped), never silently dropped.
"""

import argparse
import json
from math import comb
from pathlib import Path

import numpy as np


def load(root: Path, run: str, file: str):
    p = root / run / file
    if not p.exists():
        return None
    d = json.loads(p.read_text())
    return {(e["task"], e["init"]): bool(e["success"]) for e in d["episodes"]}, 100 * d["success_rate"]


def mcnemar(x: int, y: int) -> float:
    n, t = x + y, min(x, y)
    return min(1.0, 2 * sum(comb(n, i) for i in range(t + 1)) / 2**n) if n else 1.0


def holm(ps: list[float]) -> list[float]:
    order = np.argsort(ps)
    adj, run = [0.0] * len(ps), 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - r) * ps[i]))
        adj[i] = run
    return adj


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--manifest", default="configs/paper_manifest.json")
    ap.add_argument("--out", default=None)
    ap.add_argument("--boot", type=int, default=10000)
    args = ap.parse_args()
    root, man = Path(args.root), json.loads(Path(args.manifest).read_text())
    rng = np.random.default_rng(0)
    rows, prim = [], []
    for c in man["comparisons"]:
        file = c.get("file", "rollouts_n50.json")
        arms, missing = {}, []
        for a, runs in c["arms"].items():
            per = []
            for s, r in enumerate(runs):
                got = load(root, r, file)
                if got is None:
                    missing.append(r)
                    continue
                per.append((s, *got))
            arms[a] = per
        head = f"### {c['name']}"
        if missing:
            rows.append(f"{head}\n- missing: {', '.join(missing)}\n")
            continue
        lines = [head, "", "| arm | per seed | mean ± sd |", "|---|---|---|"]
        for a, per in arms.items():
            sr = [x[2] for x in per]
            sd = np.std(sr, ddof=1) if len(sr) > 1 else 0.0
            lines.append(f"| {a} | {' / '.join(f'{v:.1f}' for v in sr)} | {np.mean(sr):.1f} ± {sd:.1f} |")
        lines += ["", "| comparison | diff (pts) | 95% CI | discordant | McNemar p | Holm p |", "|---|---|---|---|---|---|"]
        for a, b in c["pairs"]:
            A = {(s, *k): v for s, eps, _ in arms[a] for k, v in eps.items()}
            B = {(s, *k): v for s, eps, _ in arms[b] for k, v in eps.items()}
            keys = sorted(A.keys() & B.keys())
            x = sum(A[k] and not B[k] for k in keys)
            y = sum(B[k] and not A[k] for k in keys)
            clusters = sorted({k[:2] for k in keys})
            cid = {cl: i for i, cl in enumerate(clusters)}
            d = np.zeros(len(clusters))
            n = np.zeros(len(clusters))
            for k in keys:
                d[cid[k[:2]]] += float(A[k]) - float(B[k])
                n[cid[k[:2]]] += 1
            draws = rng.integers(0, len(clusters), size=(args.boot, len(clusters)))
            boot = 100 * d[draws].sum(1) / n[draws].sum(1)
            lo, hi = np.percentile(boot, [2.5, 97.5])
            diff = 100 * d.sum() / n.sum()
            p = mcnemar(x, y)
            tag = f"{c['name']}: {a} vs {b}"
            if [a, b] in c.get("primary", []):
                prim.append((len(rows), len(lines), p))
            lines.append(f"| {a} vs {b} | {diff:+.1f} | [{lo:+.1f}, {hi:+.1f}] | {x} vs {y} | {p:.2g} | HOLM |")
        rows.append("\n".join(lines) + "\n")
    # Holm over the primary comparisons
    adj = holm([p for *_, p in prim]) if prim else []
    adj_map = {(r, l): a for (r, l, _), a in zip(prim, adj)}
    out_rows = []
    for ri, block in enumerate(rows):
        ls = block.split("\n")
        for li, l in enumerate(ls):
            if "HOLM" in l:
                ls[li] = l.replace("HOLM", f"{adj_map[(ri, li)]:.2g}" if (ri, li) in adj_map else "–")
        out_rows.append("\n".join(ls))
    text = "# Paper statistics (generated by scripts/stats_all.py; do not edit)\n\n" + "\n".join(out_rows)
    if args.out:
        Path(args.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
